"""Shared paths and helpers for the preprocessing pipeline."""
from __future__ import annotations

from pathlib import Path
import json

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
PROCESSED = ROOT / "data" / "processed"
REPORTS = ROOT / "reports"
FIGURES = REPORTS / "figures"

for p in (RAW, PROCESSED, REPORTS, FIGURES):
    p.mkdir(parents=True, exist_ok=True)

# One log entry per dataset, collected into reports/data_quality.md at the end.
_QUALITY: dict[str, dict] = {}


def save(df: pd.DataFrame, name: str) -> Path:
    """Save a processed table as Parquet (for code) and CSV (for quick inspection)."""
    pq = PROCESSED / f"{name}.parquet"
    df.to_parquet(pq, index=False)
    df.to_csv(PROCESSED / f"{name}.csv", index=False)
    print(f"  saved {name}: {len(df):,} rows x {df.shape[1]} cols")
    return pq


def log_quality(dataset: str, **facts) -> None:
    _QUALITY.setdefault(dataset, {}).update(facts)


def write_quality_report() -> Path:
    lines = ["# Data quality report", "",
             "Generated by `python src/run_all.py`. Re-run after adding new raw files.", ""]
    for ds, facts in _QUALITY.items():
        lines.append(f"## {ds}")
        lines.append("")
        for k, v in facts.items():
            if isinstance(v, (dict, list)):
                v = "`" + json.dumps(v, default=str) + "`"
            lines.append(f"- **{k}:** {v}")
        lines.append("")
    out = REPORTS / "data_quality.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Quality report -> {out}")
    return out


def adf_summary(series: pd.Series) -> dict:
    """ADF + KPSS snapshot so the review can show stationarity status per series."""
    from statsmodels.tsa.stattools import adfuller, kpss
    import warnings

    s = series.dropna().astype(float)
    if len(s) < 12:
        return {"n": len(s), "note": "too short for tests"}
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        adf_p = adfuller(s, autolag="AIC")[1]
        kpss_p = kpss(s, regression="c", nlags="auto")[1]
    verdict = "stationary" if (adf_p < 0.05 and kpss_p > 0.05) else "non-stationary (difference before ARMA)"
    return {"n": len(s), "adf_p": round(adf_p, 4), "kpss_p": round(kpss_p, 4), "verdict": verdict}
